"""Write templates/background-layers.sh, the script of background-layers.toml: a two-layer
background object on an 8x4 copy, by pokes. The copy's object is rewritten with layer A's
identity coordinates and layer B's mirrored in u, laid out vertex-major or layer-major, the
format word at a value, the tag's TSPDATASIZE 2 -> 4 (or left), the fetch from coordinate set 1
or 2. Each case runs `sgxfive-test copy --width 8 --height 4 --pixels` with its pokes and keeps
the output; nothing is judged.

    gen_background_layers.py        rewrite templates/background-layers.sh
    gen_background_layers.py -      print it
"""
from __future__ import annotations

import dataclasses
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ONE = 0x3f800000
A = [(0, 0), (ONE, 0), (0, ONE)]          # (u, v) at vertices 0, 1, 2: the identity
B = [(ONE, 0), (0, 0), (ONE, ONE)]        # mirrored in u
# The 8x4 rectangle's three vertices in the parameter-buffer form: (0, 0), (8, 0), (0, 4).
VERTS = [0x00100000, 0x1000, 0, 0x10080010, 0, 0x00100400, 0x1000, 0]


def tsp(arrangement: str) -> list[int]:
    """The 12 coordinate dwords, vertex-major (A then B per vertex) or layer-major."""
    if arrangement == "layer":
        return [w for layer in (A, B) for uv in layer for w in uv]
    return [w for i in range(3) for layer in (A, B) for w in layer[i]]


def pokes(arrangement: str, fmt: int, fset: int, tag: bool = True) -> list[str]:
    words = tsp(arrangement) + [0, fmt, 0, 0, 0, 0] + VERTS
    out = [f"bg:{3 + i}=0x{v:x}" for i, v in enumerate(words)]
    if tag:
        out.append("xfer:0^=0x06000000")
    out.append(f"pds:prim:4=0x{0x40012000 | fset:x}")
    return out


@dataclasses.dataclass(frozen=True)
class Case:
    arrangement: str
    fmt: int
    fset: int
    tag: bool = True

    @property
    def name(self) -> str:
        return f"{self.arrangement}-{self.fmt:x}-set{self.fset}{'' if self.tag else '-tag2'}"


RUNS = [Case(a, f, s) for a in ("layer", "vertex") for f in (0x404, 0x202, 0x0) for s in (1, 2)]
RUNS += [Case("vertex", 0x404, 2, False), Case("vertex", 0x404, 1, False)]
RUNS += [Case("vertex", f, 2) for f in (0xff, 0xff00, 0xffff, 0x808, 0x101, 0xffffffff)]

HEAD = """# SPDX-License-Identifier: MIT
# SPDX-FileCopyrightText: 2026 Josep Torra
# Hand-run experiments: sgxfive-test (SGXFIVE_TEST, default ~/sgxfive-test) runs each case on
# an 8x4 copy with a two-layer background object written by pokes; every output is kept and
# nothing is judged here. Generated by probes/isp/gen_background_layers.py.
set -u
T=${SGXFIVE_TEST:-$HOME/sgxfive-test}
[ -x "$T" ] || { echo "no $T: build userspace/libsgxfive for the laptop first"; exit 1; }
echo "## uname"; uname -r
run() { name=$1; shift
	echo "== $name"
	"$T" copy --width 8 --height 4 --pixels "$@" 2>&1
	echo "status $?"
}
"""


def script() -> str:
    out = HEAD
    for c in RUNS:
        args = " ".join(f"--poke {p}" for p in pokes(c.arrangement, c.fmt, c.fset, c.tag))
        out += f"run {c.name} {args}\n"
    return out


def main(argv: list[str]) -> int:
    if argv[:1] == ["-"]:
        sys.stdout.write(script())
    else:
        (HERE / "templates" / "background-layers.sh").write_text(script())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
