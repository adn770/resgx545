# item 12: one wdf over N ldad, mixed bases and offsets, TRC 31 (up to 100 destinations r20..r119).
NS = [2, 4, 8, 16, 32, 64, 100]


def off_of(i):
    """load i: (base index 0 or 1, dword offset 0..127): a permutation of 128 by an odd stride,
    every 11th load repeats the address of load 0 (a repeated line)."""
    if i and i % 11 == 0:
        return off_of(0)
    return (i % 2, (i * 37 + 5) % 128)


def gen_wdf():
    s = src("p1137_wdf", "item 12: one wdf over N ldad.bypassl1 (N = 2..100) with mixed bases and offsets; "
            "cmd 9: control, 32 loads with no wdf before the stores")
    G.prologue(s)
    G.dispatch(s, list(range(1, len(NS) + 1)) + [9])
    for k, n in enumerate(NS, 1):
        s("c%d:" % k)
        base(s, "r6", IN1)
        base(s, "r7", IN2)
        base(s, "r10", OUT1)
        for i in range(n):
            b, o = off_of(i)
            s("ldad.bypassl1 r%d, [r%d,+#%d], drc0" % (20 + i, 6 + b, o))
        s("wdf drc0")
        for i in range(n):
            s("stad [r10,+#%d], r%d" % (i, 20 + i))
        s("br @done")
    # control: preload r20..r51 from IN2 (wdf), then 32 loads from IN1 with NO wdf, stores at once
    s("c9:")
    base(s, "r6", IN1)
    base(s, "r7", IN2)
    base(s, "r10", OUT1)
    for i in range(32):
        s("ldad.bypassl1 r%d, [r7,+#%d], drc0" % (20 + i, i))
    s("wdf drc0")
    for i in range(32):
        s("ldad.bypassl1 r%d, [r6,+#%d], drc0" % (20 + i, i))
    for i in range(32):
        s("stad [r10,+#%d], r%d" % (i, 20 + i))
    s("wdf drc0", "br @done")
    G.done(s)
    return s.text()


