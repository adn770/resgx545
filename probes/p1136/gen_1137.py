# ---- the page (dwords): control 0-7, params 8-15, log 16-31, results 0x40.., then ours
IN1, IN2, OUT1, OUT2 = 256, 384, 512, 640        # host data in, results out (128 dwords each)
CNT, OVL, ARR = 960, 964, 968                    # item 14: pass counters, overlap flags, arrivals
P_, M1_, M2_ = L.PARAM_B, L.PARAM_C, L.PARAM_N   # 8, 9, 10
BUSYV, DONEV = L.BUSY, L.DONE
PHASE = "11.37"


def src(name, what, sa="No sa write, no emit, no lock."):
    return G.Src(name, what, PHASE, sa)


def base(s, reg, dword):
    s("mov %s, #0xdeadbeef                ; @patch res+0x%x" % (reg, 4 * dword))


def ldp(s, reg, dword, off=0):
    s("ldad.bypassl1 %s, [r1,+#%d], drc0" % (reg, dword))


# ============================================================================================
# item 8: predicated forms inside a task.  cmd n: p0 set from P (param 8) BEFORE the gap, the gap
# (kind), then `p0 mov r20,#A`, `!p0 mov r21,#B`, `p0 br`, `!p0 br`.  r20/r21 are preset to the
# job's own markers M1, M2 (params 9, 10); results r20 r21 r22 r23.
A_, B_ = 0x0a11ce11, 0x0b22ce22        # constants differing from every marker the host draws
HIT, MISS = 1, 2
GAPS = [("imm", 0), ("mov1", 1), ("mov4", 4), ("mov16", 16), ("mov64", 64), ("ld1", 1), ("ld4", 4),
        ("ld16", 16), ("ld32", 32), ("mix", 0), ("wdfidf", 0), ("brhop", 0)]


def gap(s, kind, n, k):
    regs = [11, 12, 13, 14, 15, 16, 17, 18, 19, 24, 25, 26, 27, 28, 29, 31]
    if kind.startswith("mov"):
        for i in range(n):
            s("mov r%d, #0x%08x" % (regs[i % len(regs)], 0x1137000 + i))
    elif kind.startswith("ld"):
        for i in range(n):
            s("ldad.bypassl1 r%d, [r1,+#%d], drc0" % (regs[i % len(regs)], IN1 % 128 + i if False else 40 + i))
        s("wdf drc0")
    elif kind == "mix":
        for i in range(4):
            s("mov r11, #0x%08x" % (0x1137100 + i), "ldad.bypassl1 r12, [r1,+#%d], drc0" % (40 + i),
              "mov r13, r11")
        s("wdf drc0", "mov r14, r12")
    elif kind == "wdfidf":
        s("wdf drc0", "idf drc0, bif", "wdf drc0")
    elif kind == "brhop":
        s("br @hop%d" % k, "mov r11, #0x00000bad", "hop%d:" % k, "mov r12, #0x00000001")


def gen_pred():
    s = src("p1137_pred", "item 8: p0 kept over a gap, predicated mov limm, p0 br and !p0 br")
    G.prologue(s)
    G.dispatch(s, list(range(1, len(GAPS) + 1)))
    for k, (kind, n) in enumerate(GAPS, 1):
        s("c%d:" % k)
        s("ldad.bypassl1 r10, [r1,+#%d], drc0" % P_, "ldad.bypassl1 r20, [r1,+#%d], drc0" % M1_,
          "ldad.bypassl1 r21, [r1,+#%d], drc0" % M2_, "wdf drc0")
        s("and.testtanz.chan0 !c0, p0, r10, r10         ; p0 = P != 0")
        gap(s, kind, n, k)
        s("p0 mov r20, #0x%08x" % A_, "!p0 mov r21, #0x%08x" % B_)
        s("p0 br @a%d" % k, "mov r22, #0x%08x" % MISS, "br @b%d" % k,
          "a%d:" % k, "mov r22, #0x%08x" % HIT,
          "b%d:" % k, "!p0 br @d%d" % k, "mov r23, #0x%08x" % MISS, "br @e%d" % k,
          "d%d:" % k, "mov r23, #0x%08x" % HIT, "e%d:" % k)
        G.result_base(s, k)
        for j, r in enumerate(("r20", "r21", "r22", "r23")):
            G.store(s, j, r)
        s("br @done")
    G.done(s)
    return s.text()


