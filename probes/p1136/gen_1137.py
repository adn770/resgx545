# item 14: a slow task with four entries (one per slot).  Every pass counts itself (the one ima32
# word: r8 = r8 - r9 with r9 = -1), flags a pass that finds state busy, logs pa0..pa2 of the last
# busy arrival; slot 0 also runs the slow loop of cmd 1 (E539's).
def gen_slow4():
    s = src("p1137_slow4", "item 14: four entries; each pass counts itself, flags a pass that finds the "
            "state busy, logs pa0..pa2 of that arrival; slot 0 also runs E539's slow loop (cmd 1)")
    for k in range(4):
        s("@entry %d" % k,
          "mov r1, #0xdeadbeef                 ; @patch res+0",
          "mov r10, #0xdeadbeef                ; @patch res+0x%x" % (4 * CNT),
          "mov r4, pa0", "mov r5, pa1", "mov r6, pa2",
          "ldad.bypassl1 r3, [r1,+#%d], drc0" % L.STATE,
          "ldad.bypassl1 r8, [r10,+#%d], drc0" % (k),
          "wdf drc0",
          "mov r9, #0xffffffff",
          "ima32.u r8, r8, #1, r9.neg",
          "stad [r10,+#%d], r8                  ; passes of slot %d" % (k, k),
          "xor.testtanz.chan0 !c0, p2, r3, #%d  ; p2 = not busy" % BUSYV,
          "p2 br @n%d" % k,
          "mov r7, #0x00000001",
          "stad [r10,+#%d], r7                  ; overlap flag of slot %d" % (OVL - CNT + k, k),
          "stad [r10,+#%d], r4" % (ARR - CNT + 4 * k), "stad [r10,+#%d], r5" % (ARR - CNT + 4 * k + 1),
          "stad [r10,+#%d], r6" % (ARR - CNT + 4 * k + 2), "idf drc0, bif", "wdf drc0",
          "n%d:" % k)
        if k == 0:
            s("ldad.bypassl1 r2, [r1,+#%d], drc0" % L.CMD, "wdf drc0",
              "and.testtanz.chan0 !c0, p0, r2, r2", "p0 br @work")
        if k == 0:
            s("tail:")
        G.tail(s, "t%d" % k, k)
    s("work:", "xor.testtaz.chan0 !c0, p1, r2, #1", "p1 br @c1", "br @t0",
      "c1:",
      "ldad.bypassl1 r8, [r1,+#%d], drc0   ; n" % L.PARAM_N, "wdf drc0",
      "mov r6, #0x%08x" % BUSYV,
      "stad [r1,+#%d], r6                  ; state = busy" % L.STATE,
      "idf drc0, bif", "wdf drc0",
      "mov r9, #0x00000001",
      "loop:", "ima32.u r8, r8, #1, r9.neg", "xor.testtanz.chan0 !c0, p1, r8, #0", "p1 br @loop",
      "br @done")
    G.done(s)
    return s.text()



# ============================================================================================
# item 15 (what the allow list permits): str then ldr of 0x0814 and 0x0a78 with a CLIENT JOB RUNNING.
# cmd 1: str V1 -> R1, ldr R1, str V2 -> R2, ldr R2 (back to back), spin N (the host starts a fill
# meanwhile), ldr R1 and R2 again, store all four reads.  Values are the job's own (params 8, 9: V1
# within 17 bits, V2 within 6 bits; param 10: N).  Nothing else is written; no clock-gate register.
R1I, R2I = 0x0814 // 4, 0x0a78 // 4


def gen_strjob():
    s = src("p1137_strjob", "item 15 (allow-list registers only): str then ldr of 0x0814 and 0x0a78, a spin "
            "of N iterations while the host runs a client fill, then ldr again")
    G.prologue(s)
    G.dispatch(s, [1])
    s("c1:")
    s("ldad.bypassl1 r10, [r1,+#%d], drc0   ; V1 (17 bits)" % P_,
      "ldad.bypassl1 r11, [r1,+#%d], drc0   ; V2 (6 bits)" % M1_,
      "ldad.bypassl1 r8, [r1,+#%d], drc0    ; N" % M2_, "wdf drc0")
    s("str #%d, r10" % R1I, "ldr r12, #%d, drc0" % R1I, "wdf drc0",
      "str #%d, r11" % R2I, "ldr r13, #%d, drc0" % R2I, "wdf drc0")
    s("mov r9, #0x00000001",
      "loop:", "ima32.u r8, r8, #1, r9.neg", "xor.testtanz.chan0 !c0, p1, r8, #0", "p1 br @loop")
    s("ldr r14, #%d, drc0" % R1I, "ldr r15, #%d, drc0" % R2I, "wdf drc0")
    G.result_base(s, 1)
    for j, r in enumerate(("r12", "r13", "r14", "r15")):
        G.store(s, j, r)
    s("br @done")
    G.done(s)
    return s.text()


def build_all():
    out = {}
    out["p1137_pred"] = gen_pred()
    out["p1137_imm"] = gen_imm()
    out["p1137_wide"] = gen_wide()
    ta, test_a = gen_regsA()
    tb, test_b = gen_regs_b()
    out["p1137_regsA"], out["p1137_regsB"] = ta, tb
    out["p1137_wdf"] = gen_wdf()
    out["p1137_slow4"] = gen_slow4()
    out["p1137_strjob"] = gen_strjob()
    return out, test_a, test_b


def main():
    ASMDIR.mkdir(exist_ok=True)
    srcs, test_a, test_b = build_all()
    rows = []
    for name, text in srcs.items():
        (ASMDIR / (name + ".s")).write_text(text)
        try:
            blob = F.build_blob_text(text)
            b = F.parse_blob(blob)
            rows.append((name, "ACCEPTED", len(b.words), hashlib.sha256(blob).hexdigest()[:16]))
            (ASMDIR / (name + ".blob")).write_bytes(blob)
        except Exception as e:
            rows.append((name, "REFUSED: " + str(e)[:80], 0, ""))
    json.dump({"test_regsA": test_a, "test_regsB": test_b, "W_A": W_A, "W_B": W_B, "NS": NS,
               "off_of": [off_of(i) for i in range(100)], "wide": WIDE, "gaps": GAPS},
              open(HERE / "layout1137.json", "w"))
    for r in rows:
        print("%-14s %-10s %4d insns  sha256 %s" % r)
    return 0 if all(r[1] == "ACCEPTED" for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
