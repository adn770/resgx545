# item 10: test immediates.  cmd 1: for n = 0..127, p0 = (V_n ^ #n) != 0 with V_n from the page;
# cmd 2: for 64 wide values W_k, p0 = (V_k ^ rK) != 0 with rK = `mov rK, #W_k` (limm).
WIDE = [128, 129, 255, 256, 257, 0x3ff, 0x400, 0x7fff, 0x8000, 0xffff, 0x10000, 0x10001, 0xfffff,
        0x100000, 0x1fffff, 0x200000, 0x3ffffff, 0x4000000, 0x7fffffff, 0x80000000, 0xffffffff,
        0xdeadbeef, 0x12345678, 0xaaaa5555, 0x5555aaaa, 0x0000ff00, 0x00ff0000, 0xff000000,
        0xffff0000, 0x00007fff, 0x0000fffe, 0xfffffffe, 0x7ffffffe, 0x80000001, 0x00200000,
        0x03e00000, 0x04000000, 0xfc000000, 0x001fffff, 0x01ffffff, 0x0000abcd, 0x1234, 0x4321,
        0xfedc, 0x2000000, 0x1ffffff, 0xf0f0f0f0, 0x0f0f0f0f, 0x80808080, 0x7f7f7f7f, 0x00010001,
        0x01010101, 0x11111111, 0x7e7e7e7e, 0x00000100, 0x00008000, 0x00800000, 0x40000000,
        0x20000000, 0x10000000, 0x08000000, 0x02000000, 0x01000000, 0x00400000]
WIDE += [0x200, 0x800, 0x1000, 0x4000, 0x20000, 0x3ffff, 0x80000, 0x1ffff, 0x40000]
WIDE = list(dict.fromkeys(WIDE))[:64]
assert len(WIDE) == 64, len(WIDE)


def _imm_head(name, what, cmds):
    s = src(name, what)
    G.prologue(s)
    G.dispatch(s, cmds)
    return s


def gen_imm():
    s = _imm_head("p1137_imm", "item 10: xor.testtanz.chan0 !c0, p0, r, #n for n = 0..127 (V_n from the page)", [1])
    s("c1:")
    base(s, "r6", IN1)
    base(s, "r10", OUT1)
    for g in range(16):
        for i in range(8):
            s("ldad.bypassl1 r%d, [r6,+#%d], drc0" % (12 + i, 8 * g + i))
        s("wdf drc0")
        for i in range(8):
            n = 8 * g + i
            s("xor.testtanz.chan0 !c0, p0, r%d, #%d" % (12 + i, n), "mov r%d, #0x00000000" % (20 + i),
              "p0 mov r%d, #0x00000001" % (20 + i))
        for i in range(8):
            s("stad [r10,+#%d], r%d" % (8 * g + i, 20 + i))
    s("br @done")
    G.done(s)
    return s.text()


def gen_wide():
    s = _imm_head("p1137_wide", "item 10: the wider n: mov rK, #W (limm) then xor.testtanz.chan0 !c0, p0, rV, rK", [1])
    s("c1:")
    base(s, "r6", IN1)
    base(s, "r10", OUT1)
    for g in range(8):
        for i in range(8):
            s("ldad.bypassl1 r%d, [r6,+#%d], drc0" % (12 + i, 8 * g + i))
        s("wdf drc0")
        for i in range(8):
            k = 8 * g + i
            s("mov r%d, #0x%08x" % (28 if i % 2 else 29, WIDE[k]),
              "xor.testtanz.chan0 !c0, p0, r%d, r%d" % (12 + i, 28 if i % 2 else 29),
              "mov r%d, #0x00000000" % (20 + i), "p0 mov r%d, #0x00000001" % (20 + i))
        for i in range(8):
            s("stad [r10,+#%d], r%d" % (8 * g + i, 20 + i))
    s("br @done")
    G.done(s)
    return s.text()


