def spec_path() -> str:
    return str(fwtask.ROOT / "doc/specs/usse_isa.md")


def spec_rows(spec: str):
    """(mask, value) of every form of the listing of doc/specs/usse_isa.md."""
    pat = re.compile(r"^#\d+\s+class \d+\s+mask ([0-9A-F]{16})\s+value ([0-9A-F]{16})\s", re.M)
    return {(int(m, 16), int(v, 16)) for m, v in pat.findall(spec)}


def in_spec(spec: str, mask: int, value: int) -> bool:
    """Whether a row of FORMS is a listing form of the spec or refines one (its mask pins every bit
    of the listing's and the value agrees there: a canonical row pins more bits, never fewer)."""
    return any(mask & m == m and value & m == v for m, v in spec_rows(spec))


KINDS = ("PLAIN", "LDR", "STR", "BR", "LAPC", "MOVLIMM", "MOVREG", "MOVPCLINK", "MOVFROMPC",
         "NOP", "IMA32", "LOAD_ABS", "STORE_ABS", "DENY", "MOVPA")


def render(regs) -> str:
    st = sorted(i for i, a in regs._allow.items() if "str" in a["use"].split("+"))
    ld = sorted(i for i, a in regs._allow.items() if "ldr" in a["use"].split("+"))
    ck = sorted(regs._clock)
    out = ["/* SPDX-License-" "Identifier: GPL-2.0-only OR MIT */",
           "/*",
           " * GENERATED by tools/fwtask/gen_verify.py from regs.toml and fwtask.FORMS: do not edit.",
           " * The register indices (dwords) a firmware task of ours may str and ldr, the clock-gate",
           " * indices refused for both, the instruction forms the verifier accepts (canonical words:",
           " * a bit no field of the form names is pinned) and the reasons it gives.",
           " */",
           "#ifndef _SGX_OWN_REGS_H_",
           "#define _SGX_OWN_REGS_H_",
           "",
           "#include <linux/compiler.h>", "#include <linux/types.h>",
           "",
           "enum sgx_own_kind {",
           "\t" + ", ".join(f"SGX_OWN_{k}" for k in KINDS) + ",",
           "};",
           ""]
    out += [f'#define SGX_OWN_WHY_{k} "{v}"' for k, v in WHYS]
    out += ["",
            "static const u16 sgx_own_clockgate_regs[] __maybe_unused = { " + ", ".join(map(str, ck)) + " };",
            "static const u16 sgx_own_str_regs[] __maybe_unused = { " + ", ".join(map(str, st)) + " };",
            "static const u16 sgx_own_ldr_regs[] __maybe_unused = { " + ", ".join(map(str, ld)) + " };",
            "",
            "/* every register offset a deny row names, for the tests: lo, hi */",
            "static const u16 sgx_own_deny[][2] __maybe_unused = {"]
    out += [f"\t{{ 0x{lo:04x}, 0x{hi:04x} }}," for lo, hi in regs.deny_ranges()]
    out += ["};", "",
            "/* first match wins; no match: refused */",
            "static const struct { u64 mask, value; u8 kind; } sgx_own_forms[] __maybe_unused = {"]
    for name, kind, mask, value in fwtask.FORMS:
        out.append(f"\t{{ 0x{mask:016x}ULL, 0x{value:016x}ULL, SGX_OWN_{kind} }},\t/* {name} */")
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


WHYS = [(k, v) for k, v in vars(fwtask.Why).items() if k.isupper()]
def crafted_blobs():
    """(name, bytes, errno name, why): blobs the kernel verifier must refuse (-EPERM, with that
    reason) or reject (-EINVAL). The same list is run by the Python verifier, by the KUnit test
    and by the host build of the kernel's verifier (test_host_verifier.py)."""
    W = fwtask.assemble_text
    P = fwtask.Patch
    Y = fwtask.Why
    ok_tail = ["nop.end"]
    res = [P(0, "res", 0)]

    def blob(lines, patches=(), entries=()):
        return fwtask.pack_blob(W("\n".join(lines)), list(patches), list(entries))

    out = []

    def add(name, data, err, why=""):
        out.append((name, data, err, why))

    for name, ins, why in (
        ("clock_str_ctl", "str #0, r1", Y.CLOCK), ("clock_str_ctl2", "str #1, r1", Y.CLOCK),
        ("clock_str_status", "str #2, r1", Y.CLOCK), ("clock_str_override", "str #3, r1", Y.CLOCK),
        ("clock_ldr_ctl", "ldr r1, #0, drc0", Y.CLOCK), ("clock_ldr_ctl2", "ldr r1, #1, drc0", Y.CLOCK),
        ("clock_ldr_status", "ldr r1, #2, drc0", Y.CLOCK),
        ("clock_ldr_override", "ldr r1, #3, drc0", Y.CLOCK),
        ("str_core_id", "str #7, r1", Y.STR), ("str_0a58", f"str #{0x0a58 // 4}, r1", Y.STR),
        ("str_0c00", f"str #{0x0c00 // 4}, r1", Y.STR), ("str_0080", f"str #{0x0080 // 4}, r1", Y.STR),
        ("str_0810", f"str #{0x0810 // 4}, r1", Y.STR), ("str_0520", f"str #{0x0520 // 4}, r1", Y.STR),
        ("ldr_unlisted", "ldr r1, #1000, drc0", Y.LDR),
        ("ldr_reg_index", "ldr r1, r2, drc0", Y.DENY), ("str_reg_index", "str r2, r1", Y.DENY),
        ("emit", "emitpix1.freep #0, r0, r1", Y.UNKNOWN),
        ("emitpds", "emitpds.tasks.taske #0, r2, r3, r4, #0x0", Y.UNKNOWN),
        ("bexception", "bexception #0", Y.UNKNOWN),
        # R3-K11: of cfi and phas only the shared exit's two words are allowed
        ("phas", "phas #0, #0, pixel, end, perinstance", Y.UNKNOWN),
        ("cfi_other", "cfi.global #1, #0, #1", Y.UNKNOWN),
        ("br_out", "br #5", Y.BR_OUT),
        # R3-K3: a mov to a pa register other than pa2 to pa4
        ("mov_pa0", "mov pa0, r1", Y.PA), ("mov_pa1", "mov pa1, r1", Y.PA),
        ("mov_pa5", "mov pa5, r1", Y.PA), ("mov_pa127", "mov pa127, r1", Y.PA),
        # R4: ba and the savelink flag are refused whole
        ("ba_in", "ba #0x4001", Y.DENY), ("ba_out", "ba #0x4010", Y.DENY),
        ("ba_savelink", "ba.savelink #0x4001", Y.DENY), ("br_savelink", "br.savelink #1", Y.DENY),
    ):
        add(name, blob([ins] + ok_tail), "EPERM", why)
    # R2: only the forms our sources use: an ALU op no source uses and the register offset, fetch,
    # increment and repeat forms of a load, a store or a move are refused
    for name, ins in (("alu_add", "xor r1, r2, r3"), ("fmad", "fmad r1, r2, r3, r4"),
                      ("stad_fetch", "stad.fetch2 [r1,+#0], r4"), ("stad_preinc", "stad [r1,++#1], r4"),
                      ("stad_regoff", "stad [r1,+r2], r4"), ("stad_sa_base", "stad [sa0,+#0], r4"),
                      ("ldad_fetch", "ldad.fetch2 r2, [r1,+#1], drc0"),
                      ("ldad_drc1", "ldad.bypassl1 r2, [r1,+#1], drc1"),
                      ("mov_repeat", "mov.repeat2 r4, r6")):
        add(name, blob(["mov r1, #0xdeadbeef", ins] + ok_tail, res, [0]), "EPERM", Y.UNKNOWN)
    # R2: a load or store base has to be the results page on every path, and the offset stays in it
    page = ["mov r1, #0xdeadbeef"]
    base_cases = {
        "base_unset": (["stad [r5,+#0], r4"], []),
        "base_loaded": (page + ["ldad.bypassl1 r2, [r1,+#1], drc0", "wdf drc0", "stad [r2,+#0], r4"], res),
        "base_overwritten": (page + ["mov r1, r4", "stad [r1,+#0], r4"], res),
        "base_limm_not_patched": (["mov r1, #0x1000", "stad [r1,+#0], r4"], []),
        "base_ldad_dst": (page + ["ldad.bypassl1 r1, [r1,+#1], drc0", "wdf drc0", "stad [r1,+#0], r4"], res),
        "base_ima32": (["mov r8, #0xdeadbeef", "ima32.u r8, r8, #1, r9.neg", "stad [r8,+#0], r4"], res),
        "base_one_path": (["p0 br #2", "mov r1, #0xdeadbeef", "stad [r1,+#0], r4"], [P(1, "res", 0)]),
        "base_past_the_page": (["mov r1, #0xdeadbeef", "stad [r1,+#127], r4"], [P(0, "res", 0xff0)]),
        "base_predicated_limm": (page + ["p0 mov r1, #0x1000", "stad [r1,+#0], r4"], res),
        "base_ldad": (["ldad.bypassl1 r2, [r5,+#1], drc0", "wdf drc0"], []),
        "base_high_reg": (["mov r40, #0xdeadbeef", "stad [r40,+#0], r4"], res),
    }
    for name, (lines, patches) in base_cases.items():
        add(name, blob(lines + ok_tail, patches, [0]), "EPERM", Y.BASE)
    # R1: the continue triple and nothing else
    c0 = [P(0, "cont0", 0)]
    cont = ["mov r30, #0xdeadbeef", "mov pclink, r30", "lapc"]
    add("patch_not_limm", blob(["nop", "nop.end"], [P(0, "res", 0)]), "EPERM", Y.PATCH_LIMM)
    add("lapc_unpatched", blob(["mov r30, #0x00000001", "mov pclink, r30", "lapc"]), "EPERM", Y.LAPC)
    add("lapc_bare", blob(["nop", "lapc"]), "EPERM", Y.LAPC)
    add("lapc_stale_limm", blob(["mov r30, #0xdeadbeef", "mov r30, #0x123", "mov pclink, r30", "lapc"],
                                c0), "EPERM", Y.LAPC)
    add("lapc_addend", blob(cont, [P(0, "cont0", 0x500)]), "EPERM", Y.PATCH_ADD)
    add("lapc_other_reg", blob(["mov r30, #0xdeadbeef", "mov pclink, r31", "lapc"], c0), "EPERM", Y.LAPC)
    add("lapc_between", blob(["mov r30, #0xdeadbeef", "nop", "mov pclink, r30", "lapc"], c0), "EPERM",
        Y.LAPC)
    add("pclink_elsewhere", blob(["mov pclink, r5", "nop.end"]), "EPERM", Y.PCLINK)
    add("pclink_then_nop", blob(cont[:2] + ["nop", "lapc"], c0), "EPERM", Y.PCLINK)
    add("pclink_bank", blob(["mov r30, #0xdeadbeef", "mov pclink, sa5", "lapc"], c0), "EPERM", Y.DENY)
    add("pclink_predicated", blob(["mov r30, #0xdeadbeef", "p0 mov pclink, r30", "lapc"], c0), "EPERM",
        Y.DENY)
    add("lapc_predicated", blob(["mov r30, #0xdeadbeef", "mov pclink, r30", "p0 lapc"], c0), "EPERM", Y.DENY)
    add("limm_predicated_patch", blob(["p0 mov r30, #0xdeadbeef", "mov pclink, r30", "lapc"], c0), "EPERM",
        Y.PATCH_LIMM)
    add("br_over_pclink", blob(["mov r30, #0xdeadbeef", "br #2", "mov pclink, r30", "lapc"], c0), "EPERM",
        Y.BR_TRIPLE)
    add("br_to_pclink", blob(cont + ["br -#0x1"], c0), "EPERM", Y.BR_TRIPLE)
    add("br_to_lapc", blob(cont + ["br -#0x2"], c0), "EPERM", Y.BR_TRIPLE)
    add("patch_twice", blob(["mov r1, #0xdeadbeef", "nop.end"], [P(0, "res", 0), P(0, "res", 8)]), "EPERM",
        Y.PATCH_TWICE)
    add("patch_res_far", blob(["mov r1, #0xdeadbeef", "nop.end"], [P(0, "res", 0x1000)]), "EPERM",
        Y.PATCH_ADD)
    add("patch_slot", blob(["mov r30, #0xdeadbeef", "nop.end"], [P(0, "cont5", 0)]), "EPERM", Y.PATCH_SLOT)
    add("patch_kind", blob(["mov r30, #0xdeadbeef", "nop.end"], [P(0, "kind7", 0)]), "EPERM", Y.PATCH_KIND)
    # R5: the last word ends the task
    add("last_nop", blob(["nop"]), "EPERM", Y.LAST)
    add("last_cond_br", blob(["nop", "p0 br -#0x1"]), "EPERM", Y.LAST)
    add("last_mov", blob(["mov r1, #0x1"]), "EPERM", Y.LAST)
    add("last_cond_through", blob(["p0 br #1", "nop.end", "nop"]), "EPERM", Y.LAST)
    add("unknown_word", fwtask.pack_blob([0x0123456789abcdef], [], []), "EPERM", Y.UNKNOWN)
    add("entry_out", fwtask.pack_blob(W("nop.end"), [], [5]), "EPERM", Y.ENTRY)
    add("entry_in_triple", blob(cont, c0, [2]), "EPERM", Y.ENTRY)
    good = blob(["nop.end"])
    add("bad_magic", b"SGXOWN02" + good[8:], "EINVAL")
    add("short", good[:20], "EINVAL")
    add("too_long", good + b"\0" * 8, "EINVAL")
    return out


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"static const u8 {name}[] = {{\n\t" + ",\n\t".join(rows) + ",\n};\n"


OK_BLOBS = ("null", "mem", "ldr", "x9b_r1", "x9b_r2", "state", "events", "slow", "trc_08", "trc_31")


def render_test_blobs(asm_dir) -> str:
    asm_dir = pathlib.Path(asm_dir)
    out = ["/* SPDX-License-" "Identifier: GPL-2.0-only OR MIT */",
           "/* GENERATED by tools/fwtask/gen_verify.py: the blobs of asm/fwtask the verifier must",
           " * accept, and crafted ones it must refuse. Do not edit. */", ""]
    for n in OK_BLOBS:
        out.append(c_array(f"own_ok_{n}", fwtask.build_blob_text((asm_dir / f"{n}.s").read_text())))
    for name, data, want, why in crafted_blobs():
        out.append(c_array(f"own_bad_{name}", data))
    out.append("static const struct { const char *name; const u8 *data; size_t len; } own_ok[] = {")
    out += [f"\t{{ \"{n}\", own_ok_{n}, sizeof(own_ok_{n}) }}," for n in OK_BLOBS]
    out.append("};\n")
    out.append("static const struct { const char *name; const u8 *data; size_t len; int err; "
               "const char *why; } own_bad[] = {")
    out += [f"\t{{ \"{n}\", own_bad_{n}, sizeof(own_bad_{n}), -{w}, \"{y}\" }}," for n, d, w, y in crafted_blobs()]
    out.append("};\n")
    return "\n".join(out)


def main(argv):
    """gen_verify.py regs OUT | blobs ASMDIR OUT"""
    if argv[1] == "regs":
        pathlib.Path(argv[2]).write_text(render(fwtask.load_regs()))
    elif argv[1] == "blobs":
        pathlib.Path(argv[3]).write_text(render_test_blobs(argv[2]))
    else:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
