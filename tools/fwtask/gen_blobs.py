"""Write asm/fwtask/*.s: the wrapper variants of phases 11.29 and 11.30, from layout.py and regs.toml.

Every file is our own source, written from the landed records (cited in its header); no closed
code is read or copied. The wrapper reads `cmd` of the results page at each entry; zero (the
1 kHz tick, the host kick) goes straight to the closed task the slot started, through a limm
that the loader patches from the replaced FACT record."""
import pathlib
import sys

import layout as L

HEADER = """; SPDX-License-Identifier: MIT
; SPDX-FileCopyrightText: 2026 Josep Torra
; {name}.s -- generated by tools/fwtask/gen_blobs.py (phase {phase}): {what}
; Written from doc/specs/usse_isa.md and the records E475/E476 (pclink, lapc), E480 (wdf with
; nothing outstanding), E512 (stad then ldad), E146/E155 (the event task, pa0 to pa2); it is run
; as an EDM task from the page the kernel maps at heap + 0x20000 (index 0x4000). Rules: r0 to r31
; only, no sa write except {sa}, no emit, no lock, every store the same value from every lane.
"""

REG = {"R1": 0x0814 // 4, "R2": 0xa78 // 4}


SA_WRITERS = "state.s, state2.s and state3.s"      # the sources that write sa (11.30)
PARAM_SA = 32       # state2, state3: the writer's parameters, dwords 32 to 40 (values), 41 to 44 (p0 to p3)
RD = {"a": 10, "b": 11, "c": 12, "d": 13}   # the reader's result slots (4 dwords each, command ids)
WRITE, READ = 1, 9


class Src:
    def __init__(self, name, what, phase="11.29", sa="state.s"):
        self.out = [HEADER.format(name=name, what=what, phase=phase, sa=sa)]

    def __call__(self, *lines):
        for ln in lines:
            self.out.append(ln if ln.startswith(("@", ";")) or ln.endswith(":") else "        " + ln)

    def text(self):
        return "\n".join(self.out) + "\n"


def prologue(s, cmd_path="work"):
    s("@entry 0",
      "mov r1, #0xdeadbeef                 ; @patch res+0",
      "ldad.bypassl1 r2, [r1,+#%d], drc0   ; cmd" % L.CMD,
      "wdf drc0",
      "and.testtanz.chan0 !c0, p0, r2, r2  ; p0 = cmd != 0",
      "p0 br @" + cmd_path)
    tail(s, "tail")


def tail(s, label, slot=0):
    s(label + ":",
      "mov r30, #0xdeadbeef                ; @patch cont%d" % slot,
      "mov pclink, r30",
      "lapc")


def done(s, fenced=True, tail_after=True):
    """results are stored: cmd = 0, fence, state = done, then the closed task (or end)."""
    s("done:",
      "mov r4, #0x00000000",
      "mov r3, #0x%08x" % L.DONE,
      "ldad.bypassl1 r5, [r1,+#%d], drc0   ; the run id, echoed" % L.RUNID,
      "wdf drc0",
      "stad [r1,+#%d], r5" % L.RUNID_ECHO,
      "stad [r1,+#%d], r4                  ; cmd = 0" % L.CMD)
    if fenced:
        s("idf drc0, bif", "wdf drc0")
    s("stad [r1,+#%d], r3                ; state = done" % L.STATE)
    if tail_after:
        s("br @tail")
    else:
        s("nop.end")


def dispatch(s, cmds):
    s("work:")
    for n in cmds:
        s("xor.testtaz.chan0 !c0, p1, r2, #%d" % n, "p1 br @c%d" % n)
    s("br @tail")


def result_base(s, n):
    s("mov r9, #0xdeadbeef                ; @patch res+%d" % (4 * L.slot(n)))


def store(s, j, reg):
    s("stad [r9,+#%d], %s" % (j, reg))


def params(s):
    s("ldad.bypassl1 r10, [r1,+#%d], drc0   ; B" % L.PARAM_B,
      "ldad.bypassl1 r11, [r1,+#%d], drc0   ; C" % L.PARAM_C,
      "wdf drc0")


def gen_null():
    s = Src("null", "stage 2: tail call only, no read, no store, no ldr, no str")
    s("@entry 0")
    tail(s, "tail")
    return s.text()


def gen_mem():
    s = Src("mem", "stage 3: memory only: store pa0, pa1, pa2 and a marker, idf, wdf (cmd 1)")
    prologue(s)
    dispatch(s, [1])
    s("c1:", "mov r4, pa0", "mov r5, pa1", "mov r6, pa2", "mov r7, #0x%08x" % 0x5a5a1129)
    result_base(s, 1)
    store(s, 0, "r4"); store(s, 1, "r5"); store(s, 2, "r6"); store(s, 3, "r7")
    s("br @done")
    done(s)
    return s.text()


def gen_ldr():
    s = Src("ldr", "stage 4: ldr only of CORE_ID, CORE_REVISION and CR_TIMER (cmd 1)")
    prologue(s)
    dispatch(s, [1])
    s("c1:", "ldr r4, #%d, drc0" % (0x1c // 4), "ldr r5, #%d, drc0" % (0x20 // 4),
      "ldr r6, #%d, drc0" % (0x144 // 4), "wdf drc0")
    result_base(s, 1)
    store(s, 0, "r4"); store(s, 1, "r5"); store(s, 2, "r6")
    s("br @done")
    done(s)
    return s.text()


def nops(s, d):
    for _ in range(d):
        s("nop")


def block_9b(s, n, kind, d, rr, other):
    """The command n of the 9b matrix on register index rr (the one under test), other is the
    index of the second register (X8)."""
    s("c%d:" % n)
    params(s)
    result_base(s, n)
    ld = lambda r, idx=rr: s("ldr %s, #%d, drc0" % (r, idx))
    st = lambda val, idx=rr: s("str #%d, %s" % (idx, val))
    wdf = lambda: s("wdf drc0")
    end = "done"
    if kind == "x0":
        ld("r12"); wdf(); store(s, 0, "r12")
    elif kind == "x1":
        ld("r12"); wdf(); st("r12"); ld("r13"); wdf(); store(s, 0, "r13"); store(s, 1, "r12")
    elif kind == "x2":
        st("r10"); nops(s, d); ld("r13"); wdf(); store(s, 0, "r13")
    elif kind == "x3":
        st("r10"); wdf(); ld("r13"); wdf(); store(s, 0, "r13")
    elif kind == "x4":
        st("r10"); s("idf drc0, bif"); wdf(); ld("r13"); wdf(); store(s, 0, "r13")
    elif kind == "x5":
        st("r10"); s("idf drc0, bif"); ld("r13"); wdf(); store(s, 0, "r13")
    elif kind == "x6":
        ld("r12"); nops(s, d); st("r10"); wdf(); store(s, 0, "r12")
    elif kind == "x7":
        st("r10"); st("r11"); ld("r13"); wdf(); store(s, 0, "r13")
    elif kind == "x8":
        st("r10"); ld("r13", other); wdf(); store(s, 0, "r13")
    elif kind == "x9":
        st("r10"); ld("r13"); wdf(); store(s, 0, "r13"); end = "done_noidf"
    elif kind == "x10":
        st("r10"); ld("r12"); wdf(); nops(s, d); ld("r13"); wdf(); store(s, 0, "r12"); store(s, 1, "r13")
    elif kind == "x11":
        ld("r14", 0x144 // 4); wdf(); st("r10"); ld("r13"); wdf(); ld("r15", 0x144 // 4); wdf()
        store(s, 0, "r13"); store(s, 1, "r14"); store(s, 2, "r15")
    s("br @" + end)


def gen_9b(reg):
    rr = REG[reg]
    other = REG["R2" if reg == "R1" else "R1"]
    s = Src("x9b_" + reg.lower(), "stages 5 and 6: the 9b matrix, str then ldr on %s (0x%04x)" % (reg, rr * 4))
    prologue(s)
    dispatch(s, sorted(L.X9B))
    for n in sorted(L.X9B):
        _, kind, d = L.X9B[n]
        block_9b(s, n, kind, d, rr, other)
    done(s)
    s("done_noidf:",
      "mov r4, #0x00000000", "mov r3, #0x%08x" % L.DONE,
      "ldad.bypassl1 r5, [r1,+#%d], drc0" % L.RUNID, "wdf drc0",
      "stad [r1,+#%d], r5" % L.RUNID_ECHO, "stad [r1,+#%d], r4" % L.CMD,
      "stad [r1,+#%d], r3                ; state = done, no idf (X9)" % L.STATE,
      "br @tail")
    return s.text()


SAV = {64: 0xa5000040, 100: 0xa5000064, 127: 0xa500007f, 20: 0xa5000014, 24: 0xa5000018}


def gen_state():
    """Item 12 and Q124. Entry: capture first (before anything touches p0 to p3 or pclink). Task 1
    cannot write pclink (the verifier refuses `mov pclink` outside the patched continue triple), so
    the pclink the second task reads is what the first left, not a value of ours."""
    s = Src("state", "item 12 and Q124: what survives between firmware tasks (cmd 1 writes, cmd 2 reads)")
    s("@entry 0",
      "mov r22, pclink",
      "mov r23, #0x00000000", "mov r24, #0x00000000", "mov r25, #0x00000000", "mov r26, #0x00000000",
      "p0 mov r23, #0x00000001", "p1 mov r24, #0x00000001", "p2 mov r25, #0x00000001",
      "p3 mov r26, #0x00000001",
      "mov r27, r20", "mov r28, r21", "mov r29, i0", "mov r31, i1")
    s("mov r1, #0xdeadbeef                 ; @patch res+0",
      "ldad.bypassl1 r2, [r1,+#%d], drc0" % L.CMD, "wdf drc0",
      "and.testtanz.chan0 !c0, p0, r2, r2", "p0 br @work")
    tail(s, "tail")
    s("work:", "xor.testtaz.chan0 !c0, p1, r2, #1", "p1 br @c1",
      "xor.testtaz.chan0 !c0, p1, r2, #2", "p1 br @c2", "br @tail")
    # cmd 2: read. Store the captured values (the sa reads here are not captures: the entry
    # code could not name them all, so they are read now; nothing between them and entry writes sa)
    s("c2:")
    result_base(s, 2)
    for j, r in enumerate(("r22", "r23", "r24", "r25")):
        store(s, j, r)
    result_base(s, 3)
    for j, r in enumerate(("r26", "r27", "r28", "r29")):
        store(s, j, r)
    s("mov r12, sa64", "mov r13, sa100", "mov r14, sa127", "mov r15, sa20", "mov r16, sa24",
      "mov r17, r31")
    result_base(s, 4)
    for j, r in enumerate(("r12", "r13", "r14", "r15")):
        store(s, j, r)
    result_base(s, 5)
    store(s, 0, "r16"); store(s, 1, "r17")
    s("br @done")
    # cmd 1: write, then arm cmd 2 for the very next event and end without the closed task
    s("c1:")
    for n, v in SAV.items():
        s("mov r12, #0x%08x" % v, "mov sa%d, r12" % n)
    s("mov r20, #0xb5000020", "mov r21, #0xb5000021", "mov i0, r20", "mov i1, r21",
      "mov r4, #0x00000000")      # (no `mov pclink`: the verifier allows it only in the continue triple)
    s("and.testtanz.chan0 !c0, p0, r12, r12",          # p0 = 1
      "and.testtanz.chan0 !c0, p1, r4, r4",            # p1 = 0 (r4 below is zero)
      "and.testtanz.chan0 !c0, p2, r12, r12", "and.testtanz.chan0 !c0, p3, r4, r4")
    s("br @done1")
    s("done1:",
      "mov r3, #0x%08x" % L.DONE, "mov r6, #0x00000002",
      "stad [r1,+#%d], r6                  ; cmd = 2: the next event reads" % L.CMD,
      "idf drc0, bif", "wdf drc0",
      "stad [r1,+#%d], r3                  ; state = done" % L.STATE,
      "nop.end")
    done(s)
    return s.text()


def gen_events():
    """Q033: four entry stubs, one per slot, each logs when pa1 != 0 and takes its own tail call."""
    s = Src("events", "Q033: four stubs log pa0, pa1, pa2 of an event with pa1 != 0, then tail on")
    for k in range(4):
        base = L.LOG + 4 * k
        s("@entry %d" % k,
          "mov r1, #0xdeadbeef                 ; @patch res+0",
          "mov r4, pa0", "mov r5, pa1", "mov r6, pa2",
          "and.testtanz.chan0 !c0, p0, r5, r5  ; p0 = pa1 != 0 (a tick has pa1 = 0)",
          "!p0 br @t%d" % k,
          "mov r7, #0x00000001",
          "stad [r1,+#%d], r7                  ; hits (a flag)" % base,
          "stad [r1,+#%d], r4                  ; last pa0" % (base + 1),
          "stad [r1,+#%d], r5                  ; last pa1" % (base + 2),
          "stad [r1,+#%d], r6                  ; last pa2" % (base + 3),
          "idf drc0, bif", "wdf drc0")
        tail(s, "t%d" % k, k)
    return s.text()


def gen_slow():
    """Item 11: can two firmware tasks overlap. cmd 1: busy, spin n, done."""
    s = Src("slow", "item 11: cmd 1 sets state busy, spins n iterations, sets done; a pass that finds busy stores overlap = 1")
    s("@entry 0",
      "mov r1, #0xdeadbeef                 ; @patch res+0",
      "ldad.bypassl1 r2, [r1,+#%d], drc0" % L.CMD,
      "ldad.bypassl1 r3, [r1,+#%d], drc0" % L.STATE,
      "wdf drc0",
      "xor.testtanz.chan0 !c0, p2, r3, #%d  ; p2 = not busy" % L.BUSY,
      "p2 br @chk",
      "mov r7, #0x00000001",
      "stad [r1,+#%d], r7                  ; overlap = 1 (a flag)" % L.OVERLAP,
      "idf drc0, bif", "wdf drc0",
      "chk:",
      "and.testtanz.chan0 !c0, p0, r2, r2", "p0 br @work")
    tail(s, "tail")
    s("work:", "xor.testtaz.chan0 !c0, p1, r2, #1", "p1 br @c1", "br @tail",
      "c1:",
      "ldad.bypassl1 r8, [r1,+#%d], drc0   ; n" % L.PARAM_N, "wdf drc0",
      "mov r6, #0x%08x" % L.BUSY,
      "stad [r1,+#%d], r6                  ; state = busy" % L.STATE,
      "idf drc0, bif", "wdf drc0",
      "mov r9, #0x00000001",
      "loop:",
      "ima32.u r8, r8, #1, r9.neg",
      "xor.testtanz.chan0 !c0, p1, r8, #0",
      "p1 br @loop",
      "br @done")
    done(s)
    return s.text()


def gen_trc(t):
    """Item 13: the marker in r(4T-1), the register past the allocation, the register r0."""
    top = min(4 * t - 1, 123)
    past = 4 * t if 4 * t <= 123 else None
    s = Src("trc_%02d" % t, "item 13: TRC %d (%d temporaries): marker in r%d" % (t, 4 * t, top))
    prologue(s)
    dispatch(s, [1])
    s("c1:", "mov r%d, #0x%08x" % (top, 0x7a110000 + t))
    if past is not None:
        s("mov r%d, #0x%08x" % (past, 0x7b220000 + t))
    s("mov r12, r%d" % top, "mov r14, r0")
    if past is not None:
        s("mov r13, r%d" % past)
    else:
        s("mov r13, #0x00000000")
    result_base(s, 1)
    store(s, 0, "r12"); store(s, 1, "r13"); store(s, 2, "r14")
    s("br @done")
    done(s)
    return s.text()


def gen_trcp(t):
    """Phase 11.33, item 13 above 31: the marker of the job (parameter 8, its own value per job) is
    written to r123, the highest register that can be named, read back with r0 and stored. T is
    the TRC the kernel arms (4T temporaries); r124 and up cannot be named, so no register past the
    allocation is written."""
    s = Src("trcp_%d" % t, "item 13: TRC %d (%d temporaries requested): the job's marker in r123" % (t, 4 * t), "11.33")
    prologue(s)
    dispatch(s, [1])
    s("c1:", "ldad.bypassl1 r10, [r1,+#%d], drc0   ; the marker" % L.PARAM_B, "wdf drc0",
      "mov r123, r10", "mov r12, r123", "mov r14, r0", "mov r13, #0x00000000")
    result_base(s, 1)
    store(s, 0, "r12"); store(s, 1, "r13"); store(s, 2, "r14")
    s("br @done")
    done(s)
    return s.text()


def gen_state2():
    """Item 12 and Q124 with a writer that tail-calls the closed task. Entry: capture first.
    cmd 1: write sa64, sa100, sa127, sa20, sa24, r20, r21, i0, i1 from the parameters and p0 to p3 from
    their flags, arm cmd 9 for the next event, state = done, then the closed task (tail call).
    cmd 9: store the values captured at entry and read sa64, sa100, sa127, sa20, sa24 now."""
    s = Src("state2", "item 12 and Q124, tail-calling writer (cmd 1) and reader (cmd 9)", "11.30", SA_WRITERS)
    s("@entry 0",
      "mov r22, pclink",
      "mov r23, #0x00000000", "mov r24, #0x00000000", "mov r25, #0x00000000", "mov r26, #0x00000000",
      "p0 mov r23, #0x00000001", "p1 mov r24, #0x00000001", "p2 mov r25, #0x00000001",
      "p3 mov r26, #0x00000001",
      "mov r27, r20", "mov r28, r21", "mov r29, i0", "mov r31, i1")
    s("mov r1, #0xdeadbeef                 ; @patch res+0",
      "ldad.bypassl1 r2, [r1,+#%d], drc0" % L.CMD, "wdf drc0",
      "and.testtanz.chan0 !c0, p0, r2, r2", "p0 br @work")
    tail(s, "tail")
    s("work:", "xor.testtaz.chan0 !c0, p1, r2, #%d" % WRITE, "p1 br @c1",
      "xor.testtaz.chan0 !c0, p1, r2, #%d" % READ, "p1 br @c9", "br @tail")
    # cmd 9: the reader
    s("c9:")
    result_base(s, RD["a"])
    for j, r in enumerate(("r22", "r23", "r24", "r25")):
        store(s, j, r)
    s("mov r12, sa64", "mov r13, sa100", "mov r14, sa127", "mov r15, sa20", "mov r16, sa24")
    result_base(s, RD["b"])
    for j, r in enumerate(("r26", "r27", "r28", "r29")):
        store(s, j, r)
    result_base(s, RD["c"])
    for j, r in enumerate(("r12", "r13", "r14", "r15")):
        store(s, j, r)
    result_base(s, RD["d"])
    store(s, 0, "r16"); store(s, 1, "r31")
    s("br @done")
    # cmd 1: the writer
    s("c1:")
    for k in range(9):
        s("ldad.bypassl1 r%d, [r1,+#%d], drc0" % (10 + k, PARAM_SA + k))
    for k in range(4):
        s("ldad.bypassl1 r%d, [r1,+#%d], drc0" % (5 + k, PARAM_SA + 9 + k))
    s("wdf drc0",
      "mov sa64, r10", "mov sa100, r11", "mov sa127, r12", "mov sa20, r13", "mov sa24, r14",
      "mov r20, r15", "mov r21, r16", "mov i0, r17", "mov i1, r18")
    s("and.testtanz.chan0 !c0, p0, r5, r5", "and.testtanz.chan0 !c0, p1, r6, r6",
      "and.testtanz.chan0 !c0, p2, r7, r7", "and.testtanz.chan0 !c0, p3, r8, r8")
    s("mov r3, #0x%08x" % L.DONE, "mov r4, #0x%08x" % READ,
      "ldad.bypassl1 r9, [r1,+#%d], drc0   ; the run id, echoed" % L.RUNID, "wdf drc0",
      "stad [r1,+#%d], r9" % L.RUNID_ECHO,
      "stad [r1,+#%d], r4                  ; cmd = 9: the next event reads" % L.CMD,
      "idf drc0, bif", "wdf drc0",
      "stad [r1,+#%d], r3                  ; state = done" % L.STATE,
      "br @tail")
    done(s)
    return s.text()


def gen_state3():
    """Stage B2: as state2 with four writer commands (1 all, 2 arm only, 3 p0 to p3 only, 4 sa, r, i
    only), two more sa (sa65, sa63; parameters 45, 46), and the reader's last slot = sa24, i1, sa65,
    sa63. Every writer arms cmd 9 for the next event and tail-calls the closed task."""
    s = Src("state3", "stage B2: writer variants (cmd 1 all, 2 arm only, 3 p only, 4 sa/r/i only) and the reader (cmd 9)", "11.30", SA_WRITERS)
    s("@entry 0",
      "mov r22, pclink",
      "mov r23, #0x00000000", "mov r24, #0x00000000", "mov r25, #0x00000000", "mov r26, #0x00000000",
      "p0 mov r23, #0x00000001", "p1 mov r24, #0x00000001", "p2 mov r25, #0x00000001",
      "p3 mov r26, #0x00000001",
      "mov r27, r20", "mov r28, r21", "mov r29, i0", "mov r31, i1")
    s("mov r1, #0xdeadbeef                 ; @patch res+0",
      "ldad.bypassl1 r2, [r1,+#%d], drc0" % L.CMD, "wdf drc0",
      "and.testtanz.chan0 !c0, p0, r2, r2", "p0 br @work")
    tail(s, "tail")
    s("work:")
    for c in (1, 2, 3, 4, 9):
        s("xor.testtaz.chan0 !c0, p1, r2, #%d" % c, "p1 br @c%d" % c)
    s("br @tail")
    s("c9:")
    result_base(s, RD["a"])
    for j, r in enumerate(("r22", "r23", "r24", "r25")):
        store(s, j, r)
    s("mov r12, sa64", "mov r13, sa100", "mov r14, sa127", "mov r15, sa20", "mov r16, sa24",
      "mov r17, sa65", "mov r18, sa63")
    result_base(s, RD["b"])
    for j, r in enumerate(("r26", "r27", "r28", "r29")):
        store(s, j, r)
    result_base(s, RD["c"])
    for j, r in enumerate(("r12", "r13", "r14", "r15")):
        store(s, j, r)
    result_base(s, RD["d"])
    store(s, 0, "r16"); store(s, 1, "r31"); store(s, 2, "r17"); store(s, 3, "r18")
    s("br @done")
    # the writers: load every parameter (r10..r18 values, r5..r8 flags, r19 and r30 are not used
    # here; sa65, sa63 come through r9 and r4 after the flags)
    s("c1:", "ldad.bypassl1 r4, [r1,+#%d], drc0" % (PARAM_SA + 14))        # sa63 value
    s("br @ld")
    s("c2:", "br @arm")
    s("c3:", "br @ldp")
    s("c4:", "ldad.bypassl1 r4, [r1,+#%d], drc0" % (PARAM_SA + 14), "br @ldv")
    s("ld:")
    s("ldv:")
    for k in range(9):
        s("ldad.bypassl1 r%d, [r1,+#%d], drc0" % (10 + k, PARAM_SA + k))
    s("ldad.bypassl1 r19, [r1,+#%d], drc0" % (PARAM_SA + 13))           # sa65 value
    s("wdf drc0",
      "mov sa64, r10", "mov sa100, r11", "mov sa127, r12", "mov sa20, r13", "mov sa24, r14",
      "mov sa65, r19", "mov sa63, r4",
      "mov r20, r15", "mov r21, r16", "mov i0, r17", "mov i1, r18")
    s("xor.testtaz.chan0 !c0, p1, r2, #4", "p1 br @arm")                 # cmd 4: no predicates
    s("ldp:")
    for k in range(4):
        s("ldad.bypassl1 r%d, [r1,+#%d], drc0" % (5 + k, PARAM_SA + 9 + k))
    s("wdf drc0",
      "and.testtanz.chan0 !c0, p0, r5, r5", "and.testtanz.chan0 !c0, p1, r6, r6",
      "and.testtanz.chan0 !c0, p2, r7, r7", "and.testtanz.chan0 !c0, p3, r8, r8")
    s("arm:",
      "mov r3, #0x%08x" % L.DONE, "mov r4, #0x%08x" % READ,
      "ldad.bypassl1 r9, [r1,+#%d], drc0   ; the run id, echoed" % L.RUNID, "wdf drc0",
      "stad [r1,+#%d], r9" % L.RUNID_ECHO,
      "stad [r1,+#%d], r4                  ; cmd = 9: the next event reads" % L.CMD,
      "idf drc0, bif", "wdf drc0",
      "stad [r1,+#%d], r3                  ; state = done" % L.STATE,
      "br @tail")
    done(s)
    return s.text()


def gen_events_m():
    """Q033: as events.s, but the log test looks at pa1 with bit 25 cleared (the tick carries it, E532)."""
    s = Src("events_m", "Q033: four stubs log pa0, pa1, pa2 of an event whose pa1 below bit 25 is non-zero", "11.30")
    for k in range(4):
        base = L.LOG + 4 * k
        s("@entry %d" % k,
          "mov r1, #0xdeadbeef                 ; @patch res+0",
          "mov r4, pa0", "mov r5, pa1", "mov r6, pa2",
          "mov r8, #0xfdffffff",
          "and.testtanz.chan0 !c0, p0, r5, r8  ; p0 = (pa1 & ~bit25) != 0",
          "!p0 br @t%d" % k,
          "mov r7, #0x00000001",
          "stad [r1,+#%d], r7                  ; hits (a flag)" % base,
          "stad [r1,+#%d], r4                  ; last pa0" % (base + 1),
          "stad [r1,+#%d], r5                  ; last pa1 (raw)" % (base + 2),
          "stad [r1,+#%d], r6                  ; last pa2" % (base + 3),
          "idf drc0, bif", "wdf drc0")
        tail(s, "t%d" % k, k)
    return s.text()


OOM_RUNGS, OOM_RING_AT, OOM_RUNG_WORDS = 48, 0x400, 8
OOM_MASK = (1 << 22) | (1 << 21) | (1 << 20) | (1 << 10) | (1 << 9) | (1 << 4)
OOM_BASES = ("r2", "r3", "r6")      # res + 0x400, + 0x600, + 0x800: 16 rungs a base register


def gen_oomring2():
    """Round 7 (R7-4 a, E918): four stubs count their passes in dwords 16 + slot and, at an event
    whose pa1 has a bit of OOM_MASK (the out-of-memory and end-of-render kinds), append a rung
    [slot + 1, pa0, pa1, sa8, sa9, CR_TIMER, CR_DPM_PAGE_STATUS, CR_DPM_GLOBAL_PAGE_STATUS] to a
    48-rung ring at res + 0x400 (dword 20 counts the rungs a full ring loses); then each goes on to
    the closed task of its slot. R5-dpm's oomring (resgx545-data render/closing-r5-dpm) with the two
    read-only loads round 7's register list allows; the blob R7-dpm's set B ran."""
    s = Src("oomring2", "Q210: four stubs append [slot + 1, pa0, pa1, sa8, sa9, CR_TIMER, 0x0724, 0x072c] "
            "to a ring at an out-of-memory or end-of-render event", "R7-4")
    for k in range(4):
        s("@entry %d" % k,
          "mov r1, #0xdeadbeef                 ; @patch res+0",
          "mov r2, #0xdeadbeef                 ; @patch res+0x%x" % OOM_RING_AT,
          "mov r3, #0xdeadbeef                 ; @patch res+0x%x" % (OOM_RING_AT + 0x200),
          "mov r6, #0xdeadbeef                 ; @patch res+0x%x" % (OOM_RING_AT + 0x400),
          "mov r10, #0x%08x                 ; the slot tag of a rung" % (k + 1),
          "mov r4, pa0", "mov r5, pa1",
          "ldad.bypassl1 r8, [r1,+#%d], drc0" % (16 + k), "wdf drc0",
          "mov r9, #0xffffffff", "ima32.u r8, r8, #1, r9.neg",
          "stad [r1,+#%d], r8                 ; passes of slot %d" % (16 + k, k),
          "idf drc0, bif", "wdf drc0",
          "mov r8, #0x%08x" % OOM_MASK,
          "and.testtanz.chan0 !c0, p0, r5, r8  ; p0 = pa1 & 0x%08x != 0" % OOM_MASK,
          "!p0 br @x%d" % k,
          "mov r12, sa8", "mov r13, sa9",
          "ldr r11, #81, drc0                  ; CR_TIMER", "wdf drc0",
          "ldr r14, #457, drc0                 ; CR_DPM_PAGE_STATUS (0x0724), read only", "wdf drc0",
          "ldr r15, #459, drc0                 ; CR_DPM_GLOBAL_PAGE_STATUS (0x072c), read only", "wdf drc0",
          "br @ring")
        tail(s, "x%d" % k, k)
    s("ring:")
    for j in range(OOM_RUNGS):
        b, o = OOM_BASES[j // 16], OOM_RUNG_WORDS * (j % 16)
        if j:
            s("r%d:" % j)
        s("ldad.bypassl1 r7, [%s,+#%d], drc0" % (b, o), "wdf drc0",
          "and.testtanz.chan0 !c0, p0, r7, r7  ; p0 = rung taken",
          "p0 br @%s" % ("r%d" % (j + 1) if j + 1 < OOM_RUNGS else "full"))
        s(*["stad [%s,+#%d], %s" % (b, o + i, r) for i, r in enumerate(("r10", "r4", "r5", "r12", "r13", "r11", "r14", "r15"))])
        s("idf drc0, bif", "wdf drc0", "br @done")
    s("full:",
      "ldad.bypassl1 r8, [r1,+#20], drc0", "wdf drc0",
      "mov r9, #0xffffffff", "ima32.u r8, r8, #1, r9.neg",
      "stad [r1,+#20], r8                 ; rungs lost to a full ring",
      "idf drc0, bif", "wdf drc0",
      "done:")
    for k in range(3):
        s("xor.testtaz.chan0 !c0, p1, r10, #%d   ; p1 = slot %d" % (k + 1, k), "p1 br @x%d" % k)
    s("br @x3")
    return s.text()


TRC_STAIRS = [8, 9, 12, 16, 24, 31, 32, 40, 48, 49, 64]
TRCP_STAIRS = [32, 36, 40, 44, 48]          # 11.33


def all_sources():
    d = {"null": gen_null(), "mem": gen_mem(), "ldr": gen_ldr(),
         "x9b_r1": gen_9b("R1"), "x9b_r2": gen_9b("R2"),
         "state": gen_state(), "events": gen_events(), "slow": gen_slow(),
         "state2": gen_state2(), "state3": gen_state3(), "events_m": gen_events_m(),
         "oomring2": gen_oomring2()}
    for t in TRC_STAIRS:
        d["trc_%02d" % t] = gen_trc(t)
    for t in TRCP_STAIRS:
        d["trcp_%d" % t] = gen_trcp(t)
    return d


def main(argv):
    """gen_blobs.py [OUTDIR]: write the sources (default: asm/fwtask)."""
    import fwtask
    out = pathlib.Path(argv[1]) if len(argv) > 1 else fwtask.ASM
    out.mkdir(parents=True, exist_ok=True)
    for name, text in all_sources().items():
        (out / (name + ".s")).write_text(text)
    print("wrote", len(all_sources()), "sources to", out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
