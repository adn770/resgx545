"""fwsim's kick builder (milestone M2, FW-4 (a)): one render job's structures as our kernel built
them for a kept session, from our own code at the commits that session ran.

- The user's command (struct drm_sgxfive_render_cmd): libsgxfive at the session tool's resgx545
  commit, against its in-process mock (host/tri_cmd.c); the library chooses every address it maps.
- The kernel's side: the linux fork's sgx_render.c and sgx_xfer.c at the session's fork commit,
  host-built with shim headers (host/kick_host.c, as tools/fwtask/host/own_host.c builds
  sgx_fw.c), around the kernel's glue at that commit (addresses, creation, the job's writes).
- The context's addresses that an allocator chose on the laptop (its kernel memory, the page
  directory, the slot) are read from the session's kept words before the job (`inputs`).

`build(session)` gives the words of the context after its creation and after the job's writes
before the kick (`init`, `job`), by render_words space (tools/usse-asm/render_words.py), plus
the TA command (`ta`), the CCB control (`ctl`), the PB block (`pbblk`) and the background
object (`bg`). Nothing here reads or holds a firmware byte: these are our kernel's structures.

    tools/fwsim/kick.py r9-c-off            the built words, a line each (`phase space:N=0x...`)
"""
from __future__ import annotations

import atexit
import functools
import gzip
import os
import pathlib
import re
import shutil
import subprocess
import sys
import io
import tarfile
import tempfile
from dataclasses import dataclass

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO / "tools" / "usse-asm"))
sys.path.insert(0, str(HERE))
import kept  # noqa: E402
import render_words  # noqa: E402

SGXFIVE = "drivers/gpu/drm/gma500/sgxfive"
UAPI = "include/uapi/drm/sgxfive_drm.h"
FWTASK_SHIM = REPO / "tools" / "fwtask" / "host" / "shim"
PARAM_BASE, PARAM_SLOT, PARAM_PT = 0x10000000, 0x800000, 0x423000
CTX_DEFINE = re.compile(r"^#define\s+(SGXFIVE_(?:CTX|RCTX|RENDER)_\w+)\s+(.*?)\s*(?:/\*.*)?$")


def _tmpdir(prefix: str) -> pathlib.Path:
    """A build directory, removed when the process exits."""
    d = pathlib.Path(tempfile.mkdtemp(prefix=prefix))
    atexit.register(shutil.rmtree, d, True)
    return d


class Unavailable(RuntimeError):
    """A source, a commit or a compiler the build needs is not here (tests skip, never pass)."""


@dataclass(frozen=True)
class Session:
    """A kept render job: its words (`DIR/CASE.words.N.txt.gz`), the fork commit its kernel was
    built from and the resgx545 commit of its tool's library, its target."""
    name: str
    path: str               # under the public data repository
    case: str
    fork: str
    tool: str
    width: int
    height: int
    cite: str


# r9-k1's c-off: `tri --pixels --keep-going --dump-render $W --words $W`, one default triangle
# 64x64 (one kick with FIRST and LAST, its render, its end), module B60AB0B4 (fork 2a650d74), tool
# t9 (resgx545 97447b04): render/closing-r9-k1/README.md.
SESSIONS = {
    "r9-c-off": Session("r9-c-off", "render/closing-r9-k1/out/20261113-083450/s0t", "c-off",
                        "2a650d74", "97447b04", 64, 64, "render/closing-r9-k1 c-off"),
}


def linux_home() -> pathlib.Path:
    return pathlib.Path(os.environ.get("RESGX545_LINUX", REPO.parent / "linux"))


def _archive(repo: pathlib.Path, commit: str, paths: list[str], into: pathlib.Path) -> None:
    r = subprocess.run(["git", "-C", str(repo), "archive", commit, *paths], capture_output=True)
    if r.returncode != 0:
        raise Unavailable(f"no {commit} with {paths} in {repo}")
    with tarfile.open(fileobj=io.BytesIO(r.stdout)) as t:
        t.extractall(into, filter="data")


def _cc() -> str:
    cc = shutil.which("cc") or shutil.which("gcc")
    if cc is None:
        raise Unavailable("no C compiler")
    return cc


def ctx_header(text: str) -> str:
    """The context-memory offsets of a fork commit's sgxfive_ctx.h (its SGXFIVE_CTX_*, _RCTX_*
    and _RENDER_* defines), alone, for the host build."""
    out = ["/* generated by tools/fwsim/kick.py from the fork's sgxfive_ctx.h */",
           "#ifndef SGXFIVE_CTX_GEN_H", "#define SGXFIVE_CTX_GEN_H",
           "#include <linux/kernel.h>", "#include <linux/sizes.h>", "#include \"sgx_xfer.h\"",
           "#ifndef PAGE_SIZE", "#define PAGE_SIZE 0x1000", "#endif"]
    for line in text.splitlines():
        if m := CTX_DEFINE.match(line):
            out.append(f"#define {m[1]} {m[2]}")
    return "\n".join(out + ["#endif", ""])


@functools.cache
def kick_host(fork: str) -> pathlib.Path:
    """host/kick_host.c built over the fork's builders at `fork`."""
    d = _tmpdir("fwsim_kick_")
    _archive(linux_home(), fork, [f"{SGXFIVE}/", UAPI], d)
    src = d / SGXFIVE
    (d / "gen").mkdir()
    (d / "gen" / "sgxfive_ctx_gen.h").write_text(ctx_header((src / "sgxfive_ctx.h").read_text()))
    (d / "gen" / "drm").mkdir()
    shutil.copy(d / UAPI, d / "gen" / "drm" / "sgxfive_drm.h")
    out = d / "kick_host"
    r = subprocess.run([_cc(), "-std=gnu11", "-O1", "-Wall", "-Wno-unused-function",
                        f"-I{HERE / 'host' / 'shim'}", f"-I{FWTASK_SHIM}", f"-I{d / 'gen'}",
                        f"-I{REPO / 'userspace' / 'libsgxfive' / 'third_party' / 'drm'}",
                        f"-I{REPO / 'userspace' / 'libsgxfive' / 'third_party' / 'compat'}", f"-I{src}",
                        "-o", str(out), str(HERE / "host" / "kick_host.c"),
                        str(src / "sgx_render.c"), str(src / "sgx_xfer.c")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"kick_host build failed:\n{r.stderr[-3000:]}")
    return out


@functools.cache
def tri_cmd_tool(tool: str) -> pathlib.Path:
    """host/tri_cmd.c linked with libsgxfive (its mock) at resgx545 `tool`."""
    d = _tmpdir("fwsim_tri_")
    _archive(REPO, tool, ["userspace/libsgxfive/", "include/uapi/"], d)
    lib = d / "userspace" / "libsgxfive"
    r = subprocess.run(["make", "-C", str(lib), "B=build", "build/libsgxfive.a"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"libsgxfive build failed:\n{r.stderr[-3000:]}")
    inc = [f"-I{lib / 'include'}", f"-I{d / 'include' / 'uapi'}", f"-I{lib / 'third_party' / 'drm'}"]
    if sys.platform != "linux":
        inc.append(f"-I{lib / 'third_party' / 'compat'}")
    out = d / "tri_cmd"
    r = subprocess.run([_cc(), "-std=c11", "-D_DEFAULT_SOURCE", "-Wall", *inc, "-o", str(out),
                        str(HERE / "host" / "tri_cmd.c"), str(lib / "build" / "libsgxfive.a")],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"tri_cmd build failed:\n{r.stderr[-3000:]}")
    return out


def user_cmd(s: Session) -> list[int]:
    """The user's render command of the session's job, as its tool's library built it."""
    r = subprocess.run([str(tri_cmd_tool(s.tool)), str(s.width), str(s.height)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"tri_cmd: {r.stderr}")
    words = {}
    for line in r.stdout.split():
        k, v = line.split("=")
        words[int(k.split(":")[1])] = int(v, 16)
    return [words[i] for i in range(len(words))]


def kept_words(s: Session, n: int, data: pathlib.Path | None = None) -> dict[str, dict[int, int]]:
    """The session's render_words file N (0: before the job, 1: after it)."""
    data = data or kept.data_dir()
    if data is None:
        raise Unavailable("no public data repository")
    p = data / s.path / f"{s.case}.words.{n}.txt.gz"
    if not p.is_file():
        raise Unavailable(f"no {p}")
    return render_words.parse(gzip.decompress(p.read_bytes()).decode())


def inputs(s: Session, data: pathlib.Path | None = None) -> dict[str, int]:
    """What an allocator chose on the laptop, read from the kept words before the job: the
    context's kernel memory (its TA CCB's address, hw_render_context word 3, the CCB at offset 0
    of the memory), its page directory (word 2) and its slot (the PB's page table, descriptor word
    4, at the slot's parameter base + 0x423000); the largest target is the job's (`tri` creates
    the context for it)."""
    w = kept_words(s, 0, data)
    pt = w["pb"][4]
    if (pt - PARAM_BASE - PARAM_PT) % PARAM_SLOT:
        raise ValueError(f"PB page table {pt:#x} is not at a slot's")
    return {"mem": w["ctx"][3], "pd_phys": w["ctx"][2], "slot": (pt - PARAM_BASE - PARAM_PT) // PARAM_SLOT,
            "max_w": s.width, "max_h": s.height}


def build(s: Session, data: pathlib.Path | None = None, *, seqno: int = 1) -> dict:
    """{"addr": {name: address}, "size": the TA command's CCB size,
        "init"/"job": {space: {word: value}}} for the session's job."""
    text = "".join(f"{k}={v:#x}\n" for k, v in {**inputs(s, data), "seqno": seqno}.items())
    text += "".join(f"cmd:{i}={v:#x}\n" for i, v in enumerate(user_cmd(s)))
    r = subprocess.run([str(kick_host(s.fork))], input=text, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"kick_host: {r.stderr}")
    out: dict = {"addr": {}, "init": {}, "job": {}}
    for line in r.stdout.splitlines():
        if line.startswith("addr "):
            k, v = line[5:].split("=")
            out["addr"][k] = int(v, 16)
        elif line.startswith("size="):
            out["size"] = int(line[5:], 16)
        else:
            phase, rest = line.split(" ")
            k, v = rest.split("=")
            space, i = k.split(":")
            out[phase].setdefault(space, {})[int(i)] = int(v, 16)
    return out


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in SESSIONS:
        print(f"usage: kick.py {{{','.join(SESSIONS)}}}", file=sys.stderr)
        return 2
    b = build(SESSIONS[argv[1]])
    for k, v in b["addr"].items():
        print(f"addr {k}={v:#010x}")
    print(f"size={b['size']:#x}")
    for phase in ("init", "job"):
        for space, words in b[phase].items():
            for i, v in sorted(words.items()):
                print(f"{phase} {space}:{i}={v:#010x}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
